import requests
import streamlit as st

API_BASE_URL = "http://localhost:8000"

st.set_page_config(
    page_title="UniBox | University Assistant",
    page_icon="🎓",
    layout="centered",
)

st.title("🎓 UniBox")
st.caption("Your university information assistant. Ask a question in your own words.")

if "messages" not in st.session_state:
    st.session_state.messages = []

with st.sidebar:
    st.subheader("About UniBox")
    st.write("Answers are generated by Gemini using the university PDFs available locally.")
    st.caption("MongoDB is not required for this version.")
    if st.button("Clear conversation", use_container_width=True):
        st.session_state.messages = []
        st.rerun()

for message in st.session_state.messages:
    with st.chat_message(message["role"]):
        st.markdown(message["content"])
        if message.get("sources"):
            with st.expander("Sources"):
                for source in message["sources"]:
                    st.write(f"• {source['source']}")

question = st.chat_input("Ask about admissions, committees, university information...")

if question:
    previous_history = [
        {"role": item["role"], "content": item["content"]}
        for item in st.session_state.messages
    ]
    st.session_state.messages.append({"role": "user", "content": question})

    with st.chat_message("user"):
        st.markdown(question)

    with st.chat_message("assistant"):
        with st.spinner("Checking university documents and preparing an answer..."):
            try:
                response = requests.post(
                    f"{API_BASE_URL}/chat",
                    json={"question": question, "history": previous_history},
                    timeout=120,
                )
                response.raise_for_status()
                data = response.json()
                answer = data["answer"]
                st.markdown(answer)

                sources = data.get("sources", [])
                if sources:
                    with st.expander("Sources"):
                        for source in sources:
                            st.write(f"• {source['source']}")

                st.session_state.messages.append({
                    "role": "assistant",
                    "content": answer,
                    "sources": sources,
                })
            except requests.exceptions.HTTPError as exc:
                detail = ""
                try:
                    detail = exc.response.json().get("detail", "")
                except Exception:
                    pass
                st.error(detail or f"API error: {exc}")
                st.session_state.messages.append({
                    "role": "assistant",
                    "content": detail or "I couldn't process that question. Please try again.",
                })
            except requests.exceptions.ConnectionError:
                error = "Cannot reach the UniBox backend. Start FastAPI first using the command in the setup instructions."
                st.error(error)
                st.session_state.messages.append({"role": "assistant", "content": error})
            except requests.exceptions.Timeout:
                error = "The request took too long. The first request can take longer while the local models load. Please try again."
                st.error(error)
                st.session_state.messages.append({"role": "assistant", "content": error})
            except requests.exceptions.RequestException as exc:
                error = f"Request failed: {exc}"
                st.error(error)
                st.session_state.messages.append({"role": "assistant", "content": error})
